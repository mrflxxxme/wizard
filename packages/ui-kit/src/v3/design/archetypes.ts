export type ArchetypeId = (typeof ARCHETYPE_IDS)[number];

/** What the system is for (goals of the brief, recognised by GOAL_STEMS in pick.ts). */
export type GoalTag = "leads" | "booking" | "sales" | "content" | "trust" | "operations" | "events";
/** Output classes of v3 (D77 (12)): business site, services with booking, CRM/admin, online shop. */
export type SystemClass = "site" | "booking" | "admin" | "shop";

export type TypeScaleId = "calm" | "classic" | "dramatic";
export type RadiusSetId = "sharp" | "crisp" | "soft" | "round";
export type Density = "compact" | "regular" | "airy";
export type GridLayout = "symmetric" | "asymmetric" | "modular" | "centered" | "split";
export type MotionProfile = "still" | "calm" | "lively";
/** Entrance of the hero (only one per page, catalog M01): none, fade, rise (opacity + 12 px), clip (reveal by mask). */
export type MotionEntrance = "none" | "fade" | "rise" | "clip";
export type MotionHover = "none" | "lift" | "underline" | "tint";
export type ImageTreatment = "natural" | "warm-grade" | "soft-grade" | "high-contrast" | "monochrome";
export type ImageRatio = "3:2" | "4:5" | "1:1" | "16:9";
export type ImageFrame = "full-bleed" | "framed" | "rounded";
/** How the brand colour is used: signal — CTA and highlights only; fill — large accent surfaces; band — one accent band. */
export type AccentUse = "signal" | "fill" | "band";
/** Surface depth (catalog E2): flat — air only, outline — 1–2 px lines, soft — a light shadow tinted by ink. */
export type Depth = "flat" | "outline" | "soft";
/** Alternate band (surface-alt): a tint of the accent, a deeper neutral, or a clearly deeper neutral. */
export type BandRule = "tint" | "neutral" | "deep";
export type Accent2Rule = "none" | "analogous" | "complement" | "split";

export interface FontPair {
  display: string;
  text: string;
  /** Why this face (required when either is a model default, fonts.ts NEEDS_REASON_FONTS); not «niche → serif». */
  why?: string;
}

export interface PaletteRules {
  /** Hues (OKLCH degrees) of the accent when the client has no brand colour; the seed picks one. */
  hues: readonly number[];
  /** Lightness and chroma range of that accent (fill in the archetype's own scheme). */
  accentL: readonly [number, number];
  accentC: readonly [number, number];
  /** Hue of the neutrals: "brand" — tinted by the accent hue, a number — a fixed hue. */
  neutralHue: "brand" | number;
  /** Chroma of the neutrals (page, surfaces, ink); the light page is never cream (catalog C02). */
  neutralC: number;
  /** Page lightness in the light and dark schemes. */
  bgL: { light: number; dark: number };
  band: BandRule;
  accent2: Accent2Rule;
  /** Scheme the page starts in. */
  scheme: "light" | "dark";
  accentUse: AccentUse;
  depth: Depth;
}

export interface Archetype {
  id: ArchetypeId;
  /** Russian name shown to the owner («три направления», V3-09). */
  name: string;
  /** Why the direction exists and what it does — the passport line for the owner and the critic. */
  why: string;
  /** The rut of the niche it deliberately avoids (catalog D3, B). */
  avoid: string;
  fontPairs: readonly FontPair[];
  /** Display weight (the catalog ships 400 and 700 only: no synthetic weights, catalog T12). */
  displayWeight: 400 | 700;
  /** Headings in capitals (short display lines only, catalog T10). */
  upper: boolean;
  /** Display tracking: tight −0.02 em, normal −0.01 em (capitals: +0.01 em). */
  tracking: "tight" | "normal";
  scales: readonly TypeScaleId[];
  radius: readonly RadiusSetId[];
  /** Controls (buttons, inputs) as pills or with the radius of the set. */
  controls: "pill" | "match";
  density: readonly Density[];
  /** Grid: columns, container, text measure (ch) and the layouts the seed picks from. */
  grid: { columns: number; maxWidth: number; measure: number; layouts: readonly GridLayout[] };
  motion: { profile: MotionProfile; entrance: MotionEntrance; hover: MotionHover };
  imagery: { style: string; treatment: ImageTreatment; ratio: ImageRatio; frame: ImageFrame };
  palette: PaletteRules;
  /** Lower-case Russian stems of niches it fits (matched as substrings of the niche). */
  niches: readonly string[];
  goals: readonly GoalTag[];
  classes: readonly SystemClass[];
  /** Voices of texts that suit it, the first is the default. */
  voices: readonly DesignVoice[];
}

