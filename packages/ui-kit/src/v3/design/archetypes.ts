/** Archetype by id, or undefined. */
export function archetype(id: string | undefined | null): Archetype | undefined {
  return id ? ARCHETYPES.find((a) => a.id === id) : undefined;
}

export const isArchetypeId = (id: unknown): id is ArchetypeId =>
  typeof id === "string" && (ARCHETYPE_IDS as readonly string[]).includes(id);
