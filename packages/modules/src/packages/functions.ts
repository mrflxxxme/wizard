// Runtime functions of «Абонементы и пакеты» (sources generated from the parameters, sdk.md). The fields a package has
// depend on what is sold (visits, a term or both), so the sources read records through plain objects:
// - packageSold (workflows package_sold, package_dates): a new package takes the term, the visits and the price of its
//   tariff and the client's contacts (a booking and the visitor cabinet find the package by them); the moment of the
//   end (`ends_at`) follows «Действует до»;
// - applyUsage (workflow package_usage_apply): a visit written off or given back by hand changes the remaining visits
//   once (the flag `applied` protects against a double count);
// - writeOffVisit / returnVisit (workflows of the booking link): a booking takes a visit off a valid package of the
//   same phone (and e-mail, when the package has one); a visitor's booking without one is cancelled at once; a
//   cancelled booking gives its visit back;
// - packageCheck (public mutation of the booking page): «is there a valid package for these contacts on this day» —
//   only yes or no, without names, terms or remaining visits;
// - unfreezePackage (workflow package_unfrozen): the days a package was frozen move its end date;
// - myMaterials (query of the page «Материалы»): the members' materials for a client with a valid package.
import type { GenContext } from "../types.js";
import { packageKind, writesOff } from "./compile.js";

