export const returnStockSource = `// Generated by the module «Интернет-магазин» (V3-23): a cancelled order gives its goods back to the stock — once, by
// the stock journal of the order (what was written off for it).
import { mutation, v } from "@wizard/sdk";

type Row = Record<string, unknown>;

export default mutation({
  args: { id: v.id("shop_order") },
  handler: async (ctx, args) => {
    const o = (await ctx.systemDb.shop_order.get(args.id)) as unknown as Row | null;
    if (!o || o.status !== "canceled" || o.stock_returned === true) return { ok: false };
    const moves = (await ctx.systemDb.stock_move.list({ where: { shop_order: args.id }, limit: 500 })) as unknown as Row[];
    const net = new Map<string, number>();
    for (const m of moves) net.set(String(m.product), (net.get(String(m.product)) ?? 0) - Number(m.qty ?? 0));
    for (const [product, qty] of net) {
      if (qty <= 0) continue;
      const p = (await ctx.systemDb.product.get(product as never)) as unknown as Row | null;
      if (!p) continue;
      const stock = typeof p.stock === "number" ? p.stock : 0;
      await ctx.systemDb.product.patch(product as never, { stock: stock + qty } as never);
      await ctx.systemDb.stock_move.insert({ product, shop_order: args.id, qty, kind: "return" } as never);
    }
    await ctx.systemDb.shop_order.patch(args.id, { stock_returned: true } as never);
    return { ok: true };
  },
});
`;

export const orderPaidSource = `// Generated by the module «Интернет-магазин» (V3-23): an order paid after its cancel (the payment page stayed open past
// the time to pay) takes its goods off the stock again; what the stock lacks is written in the shop's note.
import { mutation, v } from "@wizard/sdk";

type Row = Record<string, unknown>;

export default mutation({
  args: { id: v.id("shop_order") },
  handler: async (ctx, args) => {
    const o = (await ctx.systemDb.shop_order.get(args.id)) as unknown as Row | null;
    if (!o || o.status !== "paid" || o.stock_returned !== true) return { ok: false };
    const lines = (await ctx.systemDb.shop_order_line.list({ where: { shop_order: args.id }, limit: 100 })) as unknown as Row[];
    const short: string[] = [];
    for (const l of lines) {
      if (typeof l.product !== "string") continue;
      const p = (await ctx.systemDb.product.get(l.product as never)) as unknown as Row | null;
      if (!p) continue;
      const stock = typeof p.stock === "number" ? p.stock : 0;
      const qty = Number(l.qty ?? 0);
      const take = Math.min(stock, qty);
      if (take < qty) short.push(\`\${String(l.name ?? "Товар")}: не хватает \${qty - take} шт.\`);
      if (take <= 0) continue;
      await ctx.systemDb.product.patch(l.product as never, { stock: stock - take } as never);
      await ctx.systemDb.stock_move.insert({ product: l.product, shop_order: args.id, qty: -take, kind: "sale" } as never);
    }
    const note = short.length ? \`Оплачен после отмены. \${short.join("; ")}\`.slice(0, 300) : undefined;
    await ctx.systemDb.shop_order.patch(args.id, { stock_returned: false, ...(note ? { note } : {}) } as never);
    return { ok: true };
  },
});
`;
