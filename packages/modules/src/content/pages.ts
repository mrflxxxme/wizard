/** An entry page: the title as the h1, the date and the rubric (articles), the cover, the announcement and the body. */
function entryPage(ctx: ScreenContext, kind: "article" | "page"): string {
  const o = contentOptions(ctx.params);
  const article = kind === "article";
  const entity = article ? N.article : N.page;
  const back = article ? { label: o.blogTitle, href: R.blog } : { label: "Все страницы", href: R.pages };
  const rubric = article && o.withRubrics;
  return `// Generated by the module «Контент и блог» (V3-24): ${article ? "an article" : "a page of the site"} by the slug of the address.
import { EmptyState, LandingSection, Loading, type Rec, useDataSource } from "@wizard/ui-kit";
import { Body, day, entryHref, text, useBySlug, useSlug } from "../content/lib";

${
  rubric
    ? `function Rubric({ id }: { id: unknown }) {
  const r = useDataSource().useList<Rec>(${js(N.rubric)}, { pageSize: 24 });
  const row = (r.data?.items ?? []).find((x) => x.id === id);
  if (!row || !text(row.${N.name})) return null;
  return <a href={entryHref(${js(entryPrefix(R.rubric))}, row.${N.slug})}>{text(row.${N.name})}</a>;
}

`
    : ""
}export default function Content${article ? "Article" : "Page"}() {
  const slug = useSlug();
  const { row, isLoading } = useBySlug(${js(entity)}, slug);
  const files = useDataSource().useFiles();
  if (isLoading) return <main><Loading /></main>;
  if (!row || !text(row.${N.title}))
    return (
      <main>
        <LandingSection title="Страница не найдена" main>
          <EmptyState text=${js(MISSING)} action={<a href=${js(back.href)}>${back.label}</a>} />
        </LandingSection>
      </main>
    );
  const cover = text(row.${N.cover});
  return (
    <main>
      <LandingSection title={text(row.${N.title}) ?? ""} intro={text(row.${N.excerpt})} main>
        <article data-testid="content-entry">
${
  article
    ? `          <p>
            {day(row.${N.date}) ? <time>{day(row.${N.date})}</time> : null}
${rubric ? `            {" "}\n            <Rubric id={row.${N.rubricRef}} />\n` : ""}          </p>
`
    : ""
}          {cover ? <img src={files.imageSrc(cover, 960)} alt="" aria-hidden="true" style={{ width: "100%", height: "auto" }} /> : null}
          <Body source={row.${N.body}} />
          <p>
            <a href=${js(back.href)}>${back.label}</a>
          </p>
        </article>
      </LandingSection>
    </main>
  );
}
`;
}

export const articlePage = (ctx: ScreenContext): string => entryPage(ctx, "article");
export const sitePage = (ctx: ScreenContext): string => entryPage(ctx, "page");

/** /blog/rubric/:slug: the rubric's name and description, its articles and the other rubrics. */
export function rubricPage(ctx: ScreenContext): string {
  const o = contentOptions(ctx.params);
  return `// Generated by the module «Контент и блог» (V3-24): the articles of a rubric.
import { EmptyState, LandingSection, Loading } from "@wizard/ui-kit";
import { EntryList, RubricLinks, text, useBySlug, useSlug } from "../content/lib";

export default function ContentRubric() {
  const slug = useSlug();
  const { row, isLoading } = useBySlug(${js(N.rubric)}, slug);
  if (isLoading) return <main><Loading /></main>;
  if (!row || !text(row.${N.name}))
    return (
      <main>
        <LandingSection title="Рубрика не найдена" main>
          <EmptyState text=${js(MISSING)} action={<a href=${js(R.blog)}>${o.blogTitle}</a>} />
        </LandingSection>
      </main>
    );
  return (
    <main>
      <LandingSection title={text(row.${N.name}) ?? ""} intro={text(row.${N.description})} main>
        <RubricLinks current={slug} all={${js({ label: "Все", href: R.blog })}} />
        <EntryList entity=${js(N.article)} prefix=${js(entryPrefix(R.article))} dateField=${js(N.date)} filter={{ ${N.rubricRef}: row.id }} empty="В этой рубрике пока нет статей" />
      </LandingSection>
    </main>
  );
}
`;
}

