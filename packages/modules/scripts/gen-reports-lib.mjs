#!/usr/bin/env node
// Generates packages/modules/src/reports/lib-source.ts: the text of src/reports/lib/goalPanel.ts, which the module
// «Отчёты и панель цели» emits into a compiled system (functions/lib/goalPanel.ts, ui/lib/goalPanel.ts). The library is
// tested as code; the reports test checks this copy is up to date. Run after editing the library:
// node packages/modules/scripts/gen-reports-lib.mjs
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../..");
const lib = readFileSync(join(here, "../src/reports/lib/goalPanel.ts"), "utf8");
const out = join(here, "../src/reports/lib-source.ts");
writeFileSync(
  out,
  [
    "// GENERATED by packages/modules/scripts/gen-reports-lib.mjs from src/reports/lib/goalPanel.ts — do not edit.",
    "",
    "/** Text of lib/goalPanel.ts: emitted into a compiled system as functions/lib/goalPanel.ts and ui/lib/goalPanel.ts. */",
    "export const GOAL_PANEL_LIB =",
    "  // biome-ignore lint/suspicious/noTemplateCurlyInString: the text of a TypeScript file, not a template",
    `  ${JSON.stringify(lib)};`,
    "",
  ].join("\n"),
);
const biome = spawnSync(join(root, "node_modules/.bin/biome"), ["format", "--write", out], {
  encoding: "utf8",
});
if (biome.status !== 0) throw new Error(`biome format: ${biome.stderr}`);
console.log(`lib-source.ts: ${lib.length} chars`);
