#!/usr/bin/env node
// Generates packages/gates/data/{abuse.json,brands.ru.json} and packages/appspec/src/pii-names.data.ts (the ПДн-name
// patterns and homoglyphs shared by G2-PII-02 and module extra fields, B2-46) from specs/security/abuse.yaml#patterns
// (abuse.yaml#patterns.location). Prose entries are parsed by fixed anchors: a changed wording fails loudly.
// brands.ru.json — own compilation from abuse.yaml#patterns.brands (CC0); domains are our own list.
// Run: node packages/gates/scripts/gen-g2-data.mjs   (test/g2-data.test.ts checks the output is fresh)
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseYamlFiles } from "../../../tools/specs/validate.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
export const DATA_DIR = resolve(HERE, "../data");
export const APPSPEC_PII_FILE = resolve(HERE, "../../appspec/src/pii-names.data.ts");
const ABUSE = resolve(HERE, "../../../specs/security/abuse.yaml");

function must(m, what) {
  if (!m) throw new Error(`gen-g2-data: abuse.yaml changed, cannot parse ${what}`);
  return m;
}

const list = (s) =>
  s
    .split(",")
    .map((x) => x.trim())
    .filter(Boolean);

