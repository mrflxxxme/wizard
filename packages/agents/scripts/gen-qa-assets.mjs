#!/usr/bin/env node
// Generates packages/agents/assets/qa.json — the QA prompt fragments cut from the specs: scenario DSL
// (quality/gates.yaml#scenario_dsl), generation rules (agents/qa.yaml#checks.from_acceptance) and the reference scenarios,
// one per release class (agents/qa.yaml#checks.reference_scenarios: site, booking, crm — M2-39, D43).
// Usage: node packages/agents/scripts/gen-qa-assets.mjs [--check]
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..", "..", "..");
export const ASSET_PATH = join(ROOT, "packages/agents/assets/qa.json");

const PY_YAML =
  "import sys, json, yaml\nprint(json.dumps([yaml.safe_load(open(p, encoding='utf-8')) for p in sys.argv[1:]]))";

function loadYaml(...paths) {
  const r = spawnSync(process.env.PYTHON || "python3", ["-c", PY_YAML, ...paths], {
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });
  if (r.status !== 0) throw new Error(`YAML (python3 + PyYAML): ${r.stderr || r.error}`);
  return JSON.parse(r.stdout);
}

const kv = (obj) => Object.entries(obj).map(([k, v]) => `- ${k}: ${String(v).trim()}`);

function dslText(dsl) {
  return [
    "# DSL сценариев",
    "Scenario:",
    ...kv(dsl.Scenario),
    "Step (ровно одно действие в шаге; второй ключ — только consent у create/callFn):",
    ...kv(dsl.Step),
    "Expect:",
    ...kv(dsl.Expect),
    "Значения:",
    ...dsl.values.map((v) => `- ${v}`),
    "Исполнение:",
    ...dsl.semantics.map((v) => `- ${v}`),
  ].join("\n");
}

function rulesText(qa) {
  const f = qa.checks.from_acceptance;
  return [
    "# Правила генерации",
    `- ${f.milestone}`,
    ...f.scenario.validate.map((v) => `- ${v}`),
    `- constraint: ${f.constraint.how}`,
    ...f.constraint.examples.map((v) => `  - ${v}`),
    `- Кеш: ${qa.checks.determinism}`,
    `- Seed: ${qa.seed.rules[0]}`,
  ].join("\n");
}

/** One reference per class: "<class> (<title>): <scenario JSON>". */
function examples(qa) {
  const refs = qa.checks.reference_scenarios ?? [];
  if (refs.length === 0) throw new Error("qa.yaml#checks.reference_scenarios пуст");
  return refs.map((r) => `${r.class} (${r.title_ru}): ${JSON.stringify(r.scenario)}`);
}

export function buildAssets() {
  const [gates, qa] = loadYaml(join(ROOT, "specs/quality/gates.yaml"), join(ROOT, "specs/agents/qa.yaml"));
  const assets = {
    note: "Generated by packages/agents/scripts/gen-qa-assets.mjs from specs/ — do not edit.",
    dsl: dslText(gates.scenario_dsl),
    rules: rulesText(qa),
    categories: String(qa.explain.Explanation.category)
      .split("|")
      .map((s) => s.trim()),
    explainRules: [...qa.explain.deterministic_rules, ...qa.explain.guardrails]
      .map((s) => `- ${s}`)
      .join("\n"),
    examples: examples(qa),
  };
  return `${JSON.stringify(assets, null, 1)}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = buildAssets();
  if (process.argv.includes("--check")) {
    const same =
      existsSync(ASSET_PATH) &&
      JSON.stringify(JSON.parse(readFileSync(ASSET_PATH, "utf8"))) === JSON.stringify(JSON.parse(text));
    if (!same) {
      console.error(`${ASSET_PATH} устарел: запустите node packages/agents/scripts/gen-qa-assets.mjs`);
      process.exit(1);
    }
    console.log(`${ASSET_PATH}: актуален`);
  } else {
    writeFileSync(ASSET_PATH, text);
    console.log(`${ASSET_PATH}: ${text.length} символов`);
  }
}
