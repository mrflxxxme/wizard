const words = (s: string): string[] => s.split(/\s+/).filter(Boolean);

function uniq(xs: Iterable<string>): string[] {
  return [...new Set(xs)];
}

function diminutivesFrom(base: string): string[] {
  const out: string[] = [];
  const last = base.slice(-1);
  const stem = base.slice(0, -1);
  if (last === "а") {
    out.push(`${stem}ка`, `${stem}енька`);
  } else if (last === "я") {
    if (/[аеёиоуыэюя]$/.test(stem)) out.push(`${stem}йка`);
    else out.push(`${stem}ька`, `${stem}ечка`, `${stem}юша`);
  }
  return out.filter((w) => !GENERATED_BLOCKLIST.has(w));
}

