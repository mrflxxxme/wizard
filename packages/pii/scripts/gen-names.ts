type Entry = { form: string; flags: string; extra?: string };

// Irregular stems: explicit case forms (fleeting vowels, feminine -ь).
const EXTRA_FORMS: Record<string, string> = {
  Павел: "Павла Павлу Павлом Павле",
  Пётр: "Петра Петру Петром Петре",
  Лев: "Льва Льву Львом Льве",
  Любовь: "Любови Любовью",
  Нинель: "Нинели Нинелью",
  Лавр: "Лавра Лавру Лавром Лавре",
};

function build(): Entry[] {
  const entries = new Map<string, Entry>();
  const put = (form: string, flags: string) => {
    const prev = entries.get(form);
    if (prev) {
      // Merge flags; a form is ambiguous only if every source is ambiguous.
      const merged = new Set([...prev.flags, ...flags]);
      if (!(prev.flags.includes("a") && flags.includes("a"))) merged.delete("a");
      prev.flags = [...merged].sort().join("");
      return;
    }
    const e: Entry = { form, flags };
    const extra = EXTRA_FORMS[form];
    if (extra) e.extra = extra;
    entries.set(form, e);
  };
  const amb = (w: string) => (AMBIGUOUS.has(w) ? "a" : "");

  const male = uniq(words(MALE));
  const female = uniq(words(FEMALE));
  for (const n of male) put(n, `m${amb(n)}`);
  for (const n of female) put(n, `f${amb(n)}`);
  for (const n of words(DIMINUTIVE_M)) put(n, `md${amb(n)}`);
  for (const n of words(DIMINUTIVE_F)) put(n, `fd${amb(n)}`);
  for (const n of words(DIMINUTIVE_U)) put(n, `ud${amb(n)}`);
  for (const n of words(DIMINUTIVE_AMBIGUOUS)) put(n, "fda");
  for (const base of words(DIMINUTIVE_BASES)) {
    const g = entries.get(base)?.flags.includes("m") ? "m" : "f";
    for (const d of diminutivesFrom(base)) put(d, `${g}d${AMBIGUOUS.has(base) ? "a" : ""}`);
  }
  for (const s of uniq([...words(SURNAMES_COMMON), ...words(SURNAMES)])) put(s, "s");

  // Latin: every full name and the frequent diminutives; Latin tokens always need a surname next to them.
  const latin = new Set<string>(words(LATIN_EXTRA));
  for (const n of [...male, ...female]) for (const v of latinVariants(n)) latin.add(v);
  for (const l of latin) if (!entries.has(l)) entries.set(l, { form: l, flags: "l" });

  return [...entries.values()].sort((a, b) => (a.form < b.form ? -1 : a.form > b.form ? 1 : 0));
}

const HEADER = `# names.ru.txt — словарь имён для packages/pii (specs/security/data-boundary.yaml#detectors.kinds.person_name)
# GENERATED by packages/pii/scripts/gen-names.ts — do not edit by hand.
# Provenance: seed lists authored for this repository (general knowledge of Russian anthroponymy); derived forms
# (diminutives, Latin transliterations) generated by heuristics in the script. License: CC0-1.0 (public domain).
# Format: <form>\\t<flags>[\\t<irregular case forms>]
# Flags: m/f/u — gender; d — diminutive; a — ambiguous word (needs surname/patronymic); s — surname without a regular
#        suffix; l — Latin spelling (needs an adjacent surname). Case forms of Cyrillic names are generated at load time.
`;

function main(): void {
  const entries = build();
  const body = entries.map((e) => [e.form, e.flags, ...(e.extra ? [e.extra] : [])].join("\t")).join("\n");
  const names = entries.filter((e) => !e.flags.includes("s")).length;
  const cyrillic = entries.filter((e) => !e.flags.includes("s") && !e.flags.includes("l")).length;
  const surnames = entries.filter((e) => e.flags.includes("s")).length;
  // data-boundary.yaml: ≥ 1500 names incl. diminutives; backlog M0-05: ≥ 300 names and ≥ 300 surnames.
  if (names < 1500 || cyrillic < 300 || surnames < 300) {
    throw new Error(`dictionary too small: ${names} names, ${cyrillic} Cyrillic, ${surnames} surnames`);
  }
  writeFileSync(join(ROOT, "data/names.ru.txt"), `${HEADER}${body}\n`);
  const ts = `// GENERATED by scripts/gen-names.ts from data/names.ru.txt — do not edit by hand.\n// Provenance and license: see data/names.ru.txt header (CC0-1.0).\nexport const NAMES_DATA = \`\n${body}\n\`;\n`;
  writeFileSync(join(ROOT, "src/names.data.ts"), ts);
  const count = (f: string) => entries.filter((e) => e.flags.includes(f)).length;
  console.log(
    `names.ru.txt: ${entries.length} entries (${names} names: m=${count("m")} f=${count("f")} d=${count("d")} l=${count("l")}; surnames=${count("s")})`,
  );
}

main();
