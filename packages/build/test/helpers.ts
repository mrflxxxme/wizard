// Forum fixture: specs/appspec/examples/forum.json + specs/runtime/examples as a files map, and a
// generated @wizard/ui-kit stand-in (M0-08 pending) exporting every component the pages import.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { AppSpec } from "@wizard/appspec";
import { buildSystem } from "../src/index.js";
import type { BuildInput, BuildResult } from "../src/types.js";

export const PKG_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const REPO_ROOT = resolve(PKG_ROOT, "../..");
const EXAMPLES = join(REPO_ROOT, "specs/runtime/examples");

export function loadForum(): AppSpec {
  return JSON.parse(readFileSync(join(REPO_ROOT, "specs/appspec/examples/forum.json"), "utf8")) as AppSpec;
}

export function forumFiles(): Map<string, string> {
  const files = new Map<string, string>();
  for (const top of ["ui", "functions"]) {
    for (const f of readdirSync(join(EXAMPLES, top), { recursive: true, encoding: "utf8" }).sort()) {
      if (/\.tsx?$/.test(f))
        files.set(`${top}/${f.split("\\").join("/")}`, readFileSync(join(EXAMPLES, top, f), "utf8"));
    }
  }
  return files;
}

let stub: string | undefined;
export function uiKitStub(): string {
  if (stub) return stub;
  const names = new Set<string>();
  for (const src of forumFiles().values()) {
    for (const m of src.matchAll(/import\s*\{([^}]*)\}\s*from\s*"@wizard\/ui-kit"/g)) {
      for (const n of (m[1] ?? "").split(",")) {
        const name = n.replace(/^\s*type\s+/, "").trim();
        if (name) names.add(name);
      }
    }
  }
  const dir = join(PKG_ROOT, "test/.generated/ui-kit-stub");
  mkdirSync(dir, { recursive: true });
  const body = [
    "// generated by test/helpers.ts",
    "type P = { wzId?: string; children?: unknown; [k: string]: unknown };",
    ...[...names]
      .sort()
      .map(
        (n) =>
          `export const ${n} = (p: P) => <div data-wz-component="${n}" data-wz-id={p.wzId ?? "demo:${n}:0"}>{p.children as never}</div>;`,
      ),
    "",
  ].join("\n");
  writeFileSync(join(dir, "index.tsx"), body);
  stub = join(dir, "index.tsx");
  return stub;
}

export function build(over: Partial<BuildInput> = {}): Promise<BuildResult> {
  return buildSystem({
    spec: loadForum(),
    files: forumFiles(),
    env: "draft",
    hostModules: { uiKit: uiKitStub() },
    ...over,
  });
}

export function clientText(r: BuildResult): string {
  const dec = new TextDecoder();
  return [...r.client.values()].map((b) => dec.decode(b)).join("\n");
}
