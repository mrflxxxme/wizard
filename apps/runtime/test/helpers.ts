// value generation (satisfies the CHECK/UNIQUE constraints generated by toDDL)

let seq = 0;

export function valueFor(f: Field): unknown {
  seq += 1;
  const uniq = `${seq}${randomBytes(3).toString("hex")}`;
  switch (f.type) {
    case "int":
      return Math.max(f.min ?? 1, 1) + (seq % 5);
    case "decimal":
    case "money":
      return Math.max(f.min ?? 1, 1) + 0.5;
    case "bool":
      return true;
    case "date":
      return "2026-10-01";
    case "datetime":
      return "2026-10-01T10:00:00.000Z";
    case "enum":
      return f.enum?.[0]?.value;
    case "json":
      return { n: seq };
    case "email":
      return `u${uniq}@example.ru`;
    case "phone":
      return `+7999${String(1_000_000 + (seq % 8_999_999)).padStart(7, "0")}`;
    case "url":
      return `https://example.ru/${uniq}`;
    case "qr_token":
      return `qr_${uniq}`;
    default:
      return `v${uniq}`.slice(0, f.maxLength ?? 255);
  }
}

/** Inserts a row as the superuser (bypasses RLS); refs to entities are seeded recursively. */
export async function seedRow(
  sql: postgres.Sql,
  schema: string,
  spec: AppSpec,
  entity: string,
  overrides: Record<string, unknown> = {},
  userId?: string,
): Promise<string> {
  const e = spec.entities.find((x) => x.name === entity) as Entity;
  const row: Record<string, unknown> = { id: randomUUID() };
  for (const f of e.fields) {
    if (Object.hasOwn(overrides, f.name)) {
      row[f.name] = overrides[f.name];
      continue;
    }
    if (f.type === "ref") {
      const target = f.ref?.entity ?? "";
      if (target === USERS_ENTITY) row[f.name] = userId ?? (await seedUser(sql, schema, "organizer"));
      else if (f.required) row[f.name] = await seedRow(sql, schema, spec, target, {}, userId);
      continue;
    }
    row[f.name] = f.type === "json" ? JSON.stringify(valueFor(f)) : valueFor(f);
  }
  const cols = Object.keys(row);
  await sql.unsafe(
    `insert into ${quoteIdent(schema)}.${quoteIdent(entity)} (${cols.map(quoteIdent).join(", ")}) values (${cols
      .map((_, i) => `$${i + 1}`)
      .join(", ")})`,
    cols.map((c) => row[c]) as never[],
  );
  return row.id as string;
}

export async function seedUser(sql: postgres.Sql, schema: string, role: string): Promise<string> {
  const id = randomUUID();
  await sql.unsafe(`insert into ${quoteIdent(schema)}."users" (id, role, display_name) values ($1, $2, $3)`, [
    id,
    role,
    `seed-${role}`,
  ]);
  return id;
}

export async function userIdOf(sql: postgres.Sql, schema: string, role: string): Promise<string> {
  const rows = await sql.unsafe(`select id from ${quoteIdent(schema)}."users" where email = $1`, [
    `dev-${role}@dev.localhost`,
  ]);
  return String(rows[0]?.id);
}
